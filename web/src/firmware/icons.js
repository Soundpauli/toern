import { ROWS } from "./const.js";

const W = 12;
const H = 7;

const ICONS = {
  folder: [0x00, 0xf0, 0x00, 0x79, 0x10, 0x04, 0x41, 0x10, 0x04, 0x7f, 0x00],
  pack: [0x02, 0x60, 0x00, 0x02, 0xb0, 0x01, 0x0b, 0xc0, 0x00, 0x0c, 0x00],
  sample: [0x24, 0x40, 0x17, 0xf6, 0xf3, 0x7f, 0xf6, 0x43, 0x17, 0x24, 0x00],
  clock: [0x1c, 0xa0, 0x02, 0x49, 0x90, 0x07, 0x41, 0x20, 0x02, 0x1c, 0x00],
  volume: [0x00, 0x00, 0x00, 0x00, 0x03, 0x3c, 0xf0, 0xc3, 0x3f, 0xff, 0x03],
  settings: [0x49, 0x90, 0x0c, 0xcb, 0xb0, 0x04, 0x59, 0x90, 0x05, 0x49, 0x00],
  record: [0x63, 0x10, 0x04, 0x5d, 0xd0, 0x05, 0x5d, 0x10, 0x04, 0x63, 0x00],
  midi: [0x1c, 0xa0, 0x02, 0x41, 0x50, 0x05, 0x49, 0x20, 0x02, 0x1c, 0x00],
  song: [0x00, 0x00, 0x00, 0xbb, 0xb5, 0x5b, 0xbb, 0x05, 0x00, 0x00, 0x00],
  pattern: [0x04, 0xe0, 0x00, 0x24, 0x00, 0x07, 0x22, 0x70, 0x00, 0x02, 0x00],
};

function on(data, x, y) {
  const bit = y * W + x;
  return (data[bit >> 3] >> (bit & 7)) & 1;
}

export function showIcon(matrix, name, ox, oy, color, yOffset = 0) {
  const data = ICONS[name];
  if (!data) return;
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      if (on(data, x, y)) matrix.light(ox + x, ROWS - (oy + y) + yOffset, color);
    }
  }
}
