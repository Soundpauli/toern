export function glyphWidth(ch) {
  const c = ch.charCodeAt(0);
  if (c < 32 || c > 126) return 0;
  return ALPHABET[c - 32][0];
}

export function textPixelWidth(text) {
  let w = 0;
  for (const ch of text) {
    const c = ch.charCodeAt(0);
    if (c < 32 || c > 126) continue;
    w += ALPHABET[c - 32][0] + 1;
  }
  return w;
}
